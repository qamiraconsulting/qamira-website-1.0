// Writes api/_chat/knowledge.ts: what Qami (the site chatbot) knows about the
// services, generated from the same data the website renders.
//
// Why generated: Vercel's function bundler can't import runtime values from
// src/ (see the note at the top of api/contact.ts), so the server gets its own
// copy. It runs at the start of every build, so a catalogue change reaches the
// chatbot on the next deploy. The output is committed too, so a function never
// ships without it.
//
// Run: npx tsx scripts/build-chat-knowledge.ts

import { writeFileSync } from "node:fs";
import { catalogue, detailPaths, problems, stages } from "../src/data/content/serviceCatalogue";
import { site } from "../src/data/site";

const stageName = Object.fromEntries(stages.map((s) => [s.id, s.name]));

const services = catalogue.map((s) => ({
  code: s.code,
  name: s.name,
  stage: stageName[s.stage] ?? s.stage,
  description: s.description,
  typicalDuration: s.duration,
  page: detailPaths[s.code] ?? null,
}));

const knowledge = {
  site: { name: site.name, url: site.url, email: site.email, phone: site.phone },
  stages: stages.map((s) => ({ name: s.name, blurb: s.blurb })),
  problems: problems.map((p) => ({ label: p.label, services: p.codes })),
  services,
};

const out = `// GENERATED by scripts/build-chat-knowledge.ts -- do not edit by hand.
// Source: src/data/content/serviceCatalogue.ts and src/data/site.ts.

export const knowledge = ${JSON.stringify(knowledge, null, 2)} as const;
`;

writeFileSync(new URL("../api/_chat/knowledge.ts", import.meta.url), out);
console.log(`[chat] knowledge: ${services.length} services, ${problems.length} problems`);
